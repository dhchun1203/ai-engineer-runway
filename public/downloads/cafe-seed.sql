DROP TABLE IF EXISTS store_daily_sales;
DROP TABLE IF EXISTS order_items;
DROP TABLE IF EXISTS orders;
DROP TABLE IF EXISTS members;
DROP TABLE IF EXISTS menus;
DROP TABLE IF EXISTS stores;

-- 2. DDL: 표 다섯 개
CREATE TABLE stores (
    store_id  SERIAL PRIMARY KEY,
    name      VARCHAR(20) NOT NULL UNIQUE,
    region    VARCHAR(30) NOT NULL,
    opened_on DATE NOT NULL
);

CREATE TABLE menus (
    menu_id  SERIAL PRIMARY KEY,
    name     VARCHAR(30) NOT NULL UNIQUE,
    category VARCHAR(10) NOT NULL CHECK (category IN ('커피', '음료', '디저트')),
    price    INTEGER NOT NULL CHECK (price > 0),
    cost     INTEGER NOT NULL CHECK (cost > 0 AND cost < price)
);

CREATE TABLE members (
    member_id SERIAL PRIMARY KEY,
    nickname  VARCHAR(20) NOT NULL,
    joined_on DATE NOT NULL
);

CREATE TABLE orders (
    order_id   SERIAL PRIMARY KEY,
    store_id   INTEGER NOT NULL REFERENCES stores (store_id),
    member_id  INTEGER REFERENCES members (member_id),  -- 비회원 주문은 NULL
    ordered_at TIMESTAMP NOT NULL
);

CREATE TABLE order_items (
    order_id INTEGER NOT NULL REFERENCES orders (order_id),
    menu_id  INTEGER NOT NULL REFERENCES menus (menu_id),
    qty      INTEGER NOT NULL CHECK (qty > 0),
    PRIMARY KEY (order_id, menu_id)
);

