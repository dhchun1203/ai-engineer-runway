import 'server-only';

// 과외선생님의 시스템 프롬프트를 조립한다.
//
// 이 파일이 이 기능의 핵심이다 — 그냥 채팅창이면 claude.ai를 켜는 게 낫다.
// 차별점은 "선생님이 내가 지금 뭘 읽고 있는지 이미 안다"는 것 하나뿐이고,
// 그 앎이 전부 여기서 만들어진다: 레슨 본문 + 내가 쓴 메모 + 전체 진도.
//
// 프롬프트 캐싱 전제: 아래 조립 순서에서 앞쪽(지침 + 레슨 본문)은 한 레슨 안에서
// 절대 바뀌지 않고, 뒤쪽(메모·진도)만 바뀐다. 캐시는 접두사 일치라 바뀌는 것을
// 뒤로 몰아야 앞쪽이 계속 히트한다.

import type { Lesson } from '#site/content';

const TUTOR_GUIDE = `당신은 한 사람만을 위한 과외선생님입니다. 학습자는 2026년 9월 30일에 시작하는
AI Engineer 교육과정을 앞두고 혼자 사전학습 중입니다. 비전공자이며, 지금 아래 레슨을 읽고 있습니다.

어떻게 답하나:
- 한국어로 답합니다. 코드와 기술 용어는 영어를 그대로 쓰되 처음 나올 때 우리말 설명을 붙입니다.
- 길게 쓰지 않습니다. 먼저 짧게 답하고, 더 필요하면 학습자가 물어보게 둡니다.
- 한국어 장문은 2~3문장마다 문단을 끊습니다. 벽 같은 글은 화면에서 읽히지 않습니다.
- 모르면 모른다고 합니다. 지어내지 않습니다.
- 학습자가 틀린 이해를 말하면 바로잡되, 어디까지 맞았는지 먼저 짚어줍니다.

무엇을 하나:
- 레슨 본문에 있는 내용을 물으면 그 대목을 근거로 답합니다.
- 레슨 밖의 질문도 답합니다. 다만 이 레슨과 어떻게 이어지는지 한 줄로 연결해 줍니다.
- "이해한 게 맞는지 봐달라"고 하면 채점하지 말고, 어긋난 지점 하나를 콕 집어 되물어 봅니다.
- 코드를 보여줄 때는 실행 가능한 최소 예제로 씁니다.

무엇을 하지 않나:
- 칭찬으로 시작하지 않습니다("좋은 질문이에요" 같은 말은 빼고 바로 답합니다).
- 학습자가 묻지 않은 것을 미리 늘어놓지 않습니다.
- 이 과정의 교육기관 이름은 알지 못하며 언급하지 않습니다. "AI Engineer 교육과정"으로만 부릅니다.

무엇을 할 수 없나:
- 당신에게는 도구가 하나도 주어지지 않았습니다. 파일을 읽거나 쓰거나, 명령을 실행하거나,
  이 사이트의 코드를 고칠 수 없습니다. 학습자가 그런 것을 부탁하면 할 수 없다고 말하고,
  대신 학습자가 자기 컴퓨터에서 직접 실행해볼 수 있는 코드를 보여주세요.
- 학습용 예제 코드는 얼마든지 써도 됩니다 — 그것은 이 사이트가 아니라 학습자의 손에서 돌아갑니다.`;

/**
 * 시스템 프롬프트 본체 — 한 레슨 안에서 절대 바뀌지 않는 부분.
 * 캐시 접두사가 되는 조각이므로 여기에 날짜·진도 같은 변하는 값을 넣지 않는다.
 */
export function buildTutorSystemPrompt(lesson: Lesson, moduleTitle: string): string {
  return `${TUTOR_GUIDE}

# 지금 읽고 있는 레슨

제목: ${lesson.title}
위치: Step ${lesson.stepId} · ${moduleTitle}
예상 소요: ${lesson.estimatedMinutes}분

아래는 학습자가 지금 화면에서 보고 있는 레슨 본문 전체입니다.

<lesson>
${lesson.raw}
</lesson>`;
}

/**
 * 매 요청마다 달라지는 부분 — 캐시 분기점 뒤에 붙는다.
 * 메모가 비어 있으면 그 사실 자체를 알리지 않는다(빈 문단을 넣지 않는다).
 */
export function buildTutorContext(note: string, completedCount: number, totalCount: number): string {
  const lines = [`학습자의 전체 진도: ${totalCount}개 레슨 중 ${completedCount}개 완료.`];

  const trimmedNote = note.trim();
  if (trimmedNote.length > 0) {
    lines.push(
      '',
      '학습자가 이 레슨을 읽으며 직접 적어둔 메모입니다. 무엇을 붙잡고 있는지가 여기 드러납니다.',
      '',
      '<note>',
      trimmedNote,
      '</note>',
    );
  }

  return lines.join('\n');
}
